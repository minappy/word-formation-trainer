"""
Модуль с базой слов для тренажёра словообразования
Содержит словарь слов с их однокоренными словами, антонимами и синонимами
"""

# ========== БАЗА ДАННЫХ СЛОВ ==========
WORD_CATEGORIES = {
    "бежать": {
        "однокоренные": ["бег", "бегучий", "беговая", "пробежка", "выбежать"],
        "антонимы": ["стоять", "сидеть"],
        "синонимы": ["мчаться", "нестись", "спешить"]
    },
    "говорить": {
        "однокоренные": ["говор", "разговор", "говорун", "оговорка", "выговор"],
        "антонимы": ["молчать"],
        "синонимы": ["рассказывать", "объяснять", "беседовать"]
    },
    "свет": {
        "однокоренные": ["светлый", "светить", "освещение", "светильник", "световой"],
        "антонимы": ["темнота", "мрак"],
        "синонимы": ["сияние", "блеск"]
    },
    "работа": {
        "однокоренные": ["работать", "работник", "рабочий", "заработок", "отработать"],
        "антонимы": ["безделье", "отдых"],
        "синонимы": ["труд", "деятельность"]
    },
    "вода": {
        "однокоренные": ["водный", "водник", "водяной", "наводнение", "подводный"],
        "антонимы": ["огонь", "суша"],
        "синонимы": ["жидкость", "влага"]
    }
}


def get_categories():
    """Возвращает список доступных категорий"""
    return ["однокоренные", "антонимы", "синонимы"]


def get_words_for_category(category):
    """Возвращает слова и их значения для выбранной категории"""
    result = {}
    for word, data in WORD_CATEGORIES.items():
        if category in data:
            result[word] = data[category]
    return result


def check_answer(word, user_answer, category):
    """Проверяет ответ пользователя (регистронезависимо)"""
    if word not in WORD_CATEGORIES:
        return False
    
    correct_answers = WORD_CATEGORIES[word].get(category, [])
    user_answer_lower = user_answer.lower().strip()
    
    # Проверка: ввёл ли пользователь один из правильных ответов
    for correct in correct_answers:
        if correct.lower() == user_answer_lower:
            return True
    
    # Проверка для ответов через запятую
    parts = [p.strip().lower() for p in user_answer_lower.split(',')]
    for part in parts:
        if part in [c.lower() for c in correct_answers]:
            return True
    
    return False


def calculate_score(correct, total):
    """Рассчитывает процент правильных ответов"""
    if total == 0:
        return 0.0
    return (correct / total) * 100